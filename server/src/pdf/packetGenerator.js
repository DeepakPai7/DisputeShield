import PDFDocument from 'pdfkit';
import { db } from '../db/database.js';

export async function generateEvidencePacketPDF({ dispute, evidencePacket, analysis, letterText }) {
  // Pre-fetch product snapshot image buffer if available
  let snapshotImageBuffer = null;
  const snapshot = evidencePacket?.productSnapshot;
  if (snapshot?.main_image_url) {
    try {
      const imgRes = await fetch(snapshot.main_image_url, { signal: AbortSignal.timeout(3500) });
      if (imgRes.ok) {
        const arrBuffer = await imgRes.arrayBuffer();
        snapshotImageBuffer = Buffer.from(arrBuffer);
      }
    } catch (e) {
      // Gracefully skip image embedding if remote download fails or times out
    }
  }

  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: 'A4',
        margin: 50,
        info: {
          Title: `PayPal Dispute Response - ${dispute.paypal_dispute_id}`,
          Author: 'DisputeShield AI Legal Agent',
          Subject: `Seller Evidence Packet for ${dispute.paypal_dispute_id}`
        }
      });

      const buffers = [];
      doc.on('data', b => buffers.push(b));
      doc.on('end', () => resolve(Buffer.concat(buffers)));
      doc.on('error', err => reject(err));

      const { order, shipping, chatExcerpts = [], deliveryProof = [], accessLogs = [], gaps = [] } = evidencePacket;
      const currency = dispute.dispute_currency || 'USD';
      const sym = currency === 'INR' ? 'Rs.' : (currency === 'EUR' ? 'EUR ' : '$');

      // --- HEADER & BANNER ---
      doc.rect(50, 45, 500, 4).fill('#003087'); // PayPal deep blue top bar
      doc.fillColor('#003087').fontSize(20).font('Helvetica-Bold').text('SELLER DISPUTE RESPONSE PACKET', 50, 60);
      doc.fillColor('#666666').fontSize(10).font('Helvetica').text('Generated by DisputeShield AI for PayPal Resolution Center', 50, 85);
      doc.moveDown(1.5);

      // --- METADATA BOX ---
      const metaBoxY = doc.y;
      doc.rect(50, metaBoxY, 495, 80).fillAndStroke('#F8FAFC', '#E2E8F0');
      doc.fillColor('#0F172A').fontSize(10).font('Helvetica-Bold');

      doc.text('PayPal Dispute ID:', 65, metaBoxY + 12);
      doc.font('Helvetica').text(dispute.paypal_dispute_id, 180, metaBoxY + 12);

      doc.font('Helvetica-Bold').text('Disputed Reason:', 65, metaBoxY + 28);
      doc.font('Helvetica').text(dispute.reason, 180, metaBoxY + 28);

      doc.font('Helvetica-Bold').text('Disputed Amount:', 65, metaBoxY + 44);
      doc.font('Helvetica').text(`${sym}${dispute.dispute_amount.toFixed(2)} ${currency}`, 180, metaBoxY + 44);

      doc.font('Helvetica-Bold').text('Response Deadline:', 65, metaBoxY + 60);
      doc.font('Helvetica').text(dispute.due_date ? new Date(dispute.due_date).toLocaleDateString() : 'N/A', 180, metaBoxY + 60);

      doc.font('Helvetica-Bold').text('Merchant Order ID:', 330, metaBoxY + 12);
      doc.font('Helvetica').text(dispute.order_id || 'N/A', 440, metaBoxY + 12);

      doc.font('Helvetica-Bold').text('Customer Name:', 330, metaBoxY + 28);
      doc.font('Helvetica').text(order?.customer_name || 'N/A', 440, metaBoxY + 28);

      doc.font('Helvetica-Bold').text('Case Win Score:', 330, metaBoxY + 44);
      doc.font('Helvetica-Bold').fillColor(analysis.case_strength_score >= 80 ? '#16A34A' : '#D97706')
         .text(`${analysis.case_strength_score}/100 (${analysis.recommendation})`, 440, metaBoxY + 44);

      doc.y = metaBoxY + 95;

      // --- SECTION 1: FORMAL RESPONSE LETTER ---
      doc.fillColor('#003087').fontSize(13).font('Helvetica-Bold').text('1. Formal Defense Statement');
      doc.rect(50, doc.y + 2, 495, 1).fill('#CBD5E1');
      doc.moveDown(0.8);

      doc.fillColor('#1E293B').fontSize(9.5).font('Helvetica').text(letterText || analysis.response_letter || '', {
        align: 'left',
        lineGap: 3
      });
      doc.moveDown(1.5);

      // --- SECTION 2: CHRONOLOGICAL EVIDENCE TIMELINE ---
      if (doc.y > 620) doc.addPage();
      doc.fillColor('#003087').fontSize(13).font('Helvetica-Bold').text('2. Evidentiary Timeline & Verification');
      doc.rect(50, doc.y + 2, 495, 1).fill('#CBD5E1');
      doc.moveDown(0.8);

      if (shipping) {
        doc.fillColor('#0F172A').fontSize(10).font('Helvetica-Bold').text(`Logistics & Tracking (${shipping.carrier}):`);
        doc.fillColor('#334155').fontSize(9).font('Helvetica').text(`Tracking Number: ${shipping.tracking_number} | Status: ${shipping.status}`);
        if (shipping.delivered_at) {
          doc.text(`Delivered Timestamp: ${shipping.delivered_at}`);
        }
        if (shipping.recipient_signature) {
          doc.fillColor('#16A34A').font('Helvetica-Bold').text(`[CONFIRMED SIGNATURE]: ${shipping.recipient_signature}`);
        }
        if (shipping.unique_delivery_id) {
          doc.fillColor('#0284C7').font('Helvetica-Bold').text(`[OTP HANDSHAKE PROOF]: Unique Verification ID #${shipping.unique_delivery_id}`);
        }

        if (shipping.events && shipping.events.length > 0) {
          doc.moveDown(0.4);
          doc.fillColor('#475569').font('Helvetica-Oblique').fontSize(8.5);
          for (const ev of shipping.events.slice(-4)) {
            doc.text(`• ${ev.event_time}: ${ev.description} (${ev.location || ''})`);
          }
        }
        doc.moveDown(1);
      }

      // --- SECTION 3: COMMUNICATIONS & TELEMETRY ---
      if (chatExcerpts.length > 0) {
        if (doc.y > 620) doc.addPage();
        doc.fillColor('#0F172A').fontSize(10).font('Helvetica-Bold').text('Customer Communications Transcripts:');
        doc.fillColor('#334155').fontSize(9).font('Helvetica');
        for (const chat of chatExcerpts) {
          doc.text(`[${chat.sent_at}] ${chat.channel} | ${chat.sender}: "${chat.message_text}"`);
        }
        doc.moveDown(1);
      }

      if (accessLogs.length > 0) {
        if (doc.y > 620) doc.addPage();
        doc.fillColor('#0F172A').fontSize(10).font('Helvetica-Bold').text('Digital Delivery & Access Telemetry:');
        doc.fillColor('#334155').fontSize(9).font('Helvetica');
        for (const log of accessLogs.slice(0, 5)) {
          doc.text(`• ${log.logged_at} | IP: ${log.ip_address} | Action: ${log.action}`);
        }
        doc.moveDown(1);
      }

      // --- SECTION 3: LISTING SNAPSHOT AT TIME OF SALE (CHANNEL3 CATALOG EVIDENCE) ---
      if (snapshot) {
        if (doc.y > 560) doc.addPage();
        doc.fillColor('#003087').fontSize(13).font('Helvetica-Bold').text('3. Product Listing at Time of Sale');
        doc.rect(50, doc.y + 2, 495, 1).fill('#CBD5E1');
        doc.moveDown(0.8);

        const snapBoxY = doc.y;
        const boxHeight = snapshotImageBuffer ? 95 : 75;
        doc.rect(50, snapBoxY, 495, boxHeight).fillAndStroke('#F8FAFC', '#E2E8F0');

        let textX = 65;
        if (snapshotImageBuffer) {
          try {
            doc.image(snapshotImageBuffer, 60, snapBoxY + 8, { width: 75, height: 75, fit: [75, 75] });
            textX = 145;
          } catch (e) {
            textX = 65;
          }
        }

        doc.fillColor('#0F172A').fontSize(10).font('Helvetica-Bold').text(snapshot.title, textX, snapBoxY + 8, { width: 490 - textX });
        doc.fontSize(8.5).font('Helvetica').fillColor('#475569');
        doc.text(`Brand: ${snapshot.brand || 'Unbranded'}  |  Listed Price: $${Number(snapshot.price).toFixed(2)} ${snapshot.currency}  |  Retailer: ${snapshot.offer_domain || 'Online Store'}`, textX, doc.y + 2);
        doc.text(`Channel3 Product ID: ${snapshot.channel3_product_id}  |  Snapshot Reference: #${snapshot.id}`, textX, doc.y + 2);
        doc.text(`Captured: ${new Date(snapshot.captured_at).toLocaleString()}`, textX, doc.y + 2);

        if (snapshot.description) {
          doc.fillColor('#64748B').fontSize(7.5).font('Helvetica-Oblique').text(
            `"${snapshot.description.slice(0, 150)}${snapshot.description.length > 150 ? '...' : ''}"`,
            textX,
            doc.y + 3,
            { width: 490 - textX }
          );
        }

        doc.y = snapBoxY + boxHeight + 10;
      }

      // --- SECTION 4: DECLARATION ---
      if (doc.y > 640) doc.addPage();
      doc.moveDown(0.5);
      doc.rect(50, doc.y, 495, 60).fillAndStroke('#F1F5F9', '#CBD5E1');
      const decY = doc.y + 8;
      doc.fillColor('#334155').fontSize(8.5).font('Helvetica-Bold').text('SELLER DECLARATION OF TRUTH', 65, decY);
      doc.font('Helvetica').fontSize(8).fillColor('#64748B').text(
        'I hereby certify that the documentation and timeline presented in this response packet represent true and contemporaneous records of order fulfillment and customer interaction, submitted in accordance with PayPal Seller Protection Policies.',
        65,
        decY + 14,
        { width: 465 }
      );

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}

export default { generateEvidencePacketPDF };

